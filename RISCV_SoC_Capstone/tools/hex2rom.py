#!/usr/bin/env python3
"""rom.hex -> synthesizable case-ROM (module rom, same ports as rom.v). Usage: hex2rom.py in.hex out.v [WORDS]"""
import sys
words = [l.strip() for l in open(sys.argv[1]) if l.strip()]
n = int(sys.argv[3]) if len(sys.argv) > 3 else 1024
ab = (n - 1).bit_length()
o = ["// AUTO-GENERATED by tools/hex2rom.py - synthesizable ROM, no initial blocks",
     f"module rom #(parameter WORDS = {n}) (",
     "  input clk, input rst_n,",
     "  input [31:0] s_awaddr, input s_awvalid, output s_awready,",
     "  input [31:0] s_wdata, input [3:0] s_wstrb, input s_wvalid, output s_wready,",
     "  output [1:0] s_bresp, output s_bvalid, input s_bready,",
     "  input [31:0] s_araddr, input s_arvalid, output s_arready,",
     "  output [31:0] s_rdata, output [1:0] s_rresp, output s_rvalid, input s_rready);",
     "  wire [31:0] ra; reg [31:0] rd;",
     "  axil_reg_if u_if (.clk(clk), .rst_n(rst_n),",
     "    .s_awaddr(s_awaddr), .s_awvalid(s_awvalid), .s_awready(s_awready),",
     "    .s_wdata(s_wdata), .s_wstrb(s_wstrb), .s_wvalid(s_wvalid), .s_wready(s_wready),",
     "    .s_bresp(s_bresp), .s_bvalid(s_bvalid), .s_bready(s_bready),",
     "    .s_araddr(s_araddr), .s_arvalid(s_arvalid), .s_arready(s_arready),",
     "    .s_rdata(s_rdata), .s_rresp(s_rresp), .s_rvalid(s_rvalid), .s_rready(s_rready),",
     "    .reg_we(), .reg_wa(), .reg_wd(), .reg_ws(), .reg_re(), .reg_ra(ra), .reg_rd(rd));",
     "  always @* begin",
     f"    case (ra[{ab+1}:2])"]
for i, w in enumerate(words[:n]):
    o.append(f"      {ab}'d{i}: rd = 32'h{w};")
o += ["      default: rd = 32'h0000_0013; // nop", "    endcase", "  end", "endmodule"]
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
