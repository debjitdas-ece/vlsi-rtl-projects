#!/usr/bin/env python3
"""Summarise Verilator coverage.dat -> docs/coverage.md (block / branch / toggle %). Usage: cov_summary.py coverage.dat out.md"""
import re, sys, collections
tot = collections.defaultdict(lambda: [0, 0])          # type -> [hit, total]
for line in open(sys.argv[1]):
    if not line.startswith("C '"): continue
    m = re.match(r"C '(.*?)' (\d+)$", line.rstrip("\n"))
    if not m: continue
    body, cnt = m.group(1), int(m.group(2))
    # fields are separated by \x01 key \x02 value
    kv = dict(f.split("\x02", 1) for f in body.split("\x01") if "\x02" in f)
    page = kv.get("page", "")
    if "picorv32" in kv.get("f", ""): continue          # third-party core excluded
    kind = page.split("/")[0].replace("v_", "")
    tot[kind][1] += 1
    tot[kind][0] += 1 if cnt > 0 else 0
names = {"line": "Block (line)", "branch": "Branch", "toggle": "Toggle"}
out = ["# Verilator coverage (our RTL only, PicoRV32 excluded)\n", "| Metric | Hit | Total | % |", "|---|---|---|---|"]
for k, label in names.items():
    h, t = tot.get(k, [0, 0])
    out.append(f"| {label} | {h} | {t} | {100.0*h/t:.1f} |" if t else f"| {label} | 0 | 0 | n/a |")
out.append("\nGenerated by `make cov` (full SoC-plus firmware run). Line coverage here is per block, not per statement.")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("\n".join(out))
